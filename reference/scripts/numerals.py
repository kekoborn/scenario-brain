"""Числа прописью → цифрами. Только КОЛИЧЕСТВА, не риторика.
«сто пятьдесят миллиардов» → «150 миллиардов» (множитель остаётся словом — так читается вслух).
dry-run по умолчанию; запись: --apply"""
import re, sys, json
from collections import Counter

D = "/Users/ruslanalyev/.claude/skills/scenario-brain/sessions/konkurentnaya-razvedka"

ONES = {"ноль":0,"один":1,"одна":1,"одно":1,"одну":1,"одного":1,"два":2,"две":2,"двух":2,"три":3,"трёх":3,
 "трех":3,"четыре":4,"четырёх":4,"четырех":4,"пять":5,"пяти":5,"шесть":6,"шести":6,"семь":7,"семи":7,
 "восемь":8,"восьми":8,"девять":9,"девяти":9,"десять":10,"десяти":10,"одиннадцать":11,"двенадцать":12,
 "тринадцать":13,"тринадцати":13,"четырнадцать":14,"пятнадцать":15,"пятнадцати":15,"шестнадцать":16,
 "семнадцать":17,"семнадцати":17,"восемнадцать":18,"девятнадцать":19}
TENS = {"двадцать":20,"двадцати":20,"тридцать":30,"тридцати":30,"сорок":40,"сорока":40,"пятьдесят":50,
 "пятидесяти":50,"шестьдесят":60,"шестидесяти":60,"семьдесят":70,"семидесяти":70,"восемьдесят":80,
 "восьмидесяти":80,"девяносто":90,"девяноста":90}
HUNDREDS = {"сто":100,"ста":100,"двести":200,"двухсот":200,"триста":300,"трёхсот":300,"четыреста":400,
 "пятьсот":500,"пятисот":500,"шестьсот":600,"шестисот":600,"семьсот":700,"семисот":700,"восемьсот":800,
 "девятьсот":900}
NUM = {**ONES, **TENS, **HUNDREDS}
# множитель ОСТАЁТСЯ словом: «150 миллиардов» читается, «150 000 000 000» — нет
MULT = {"тысяча":"тысяча","тысячи":"тысячи","тысяч":"тысяч","тысячу":"тысячу",
        "миллион":"миллион","миллиона":"миллиона","миллионов":"миллионов",
        "миллиард":"миллиард","миллиарда":"миллиарда","миллиардов":"миллиардов"}

UNIT = (r'процент\w*|рубл\w+|копе\w+|₽|раз\b|раза\b|лет\b|год\w*|мес\w*|дн\w+|день\b|брендов|категори\w+|'
        r'компани\w+|проект\w+|филиал\w+|город\w+|амбассадор\w+|охват\w+|интеграци\w+|реклам\w*|'
        r'заяв\w+|лид\w*|клиент\w+|человек\w*|тест\w+|шаг\w+|операци\w+|конверси\w+|подписчик\w+|'
        r'сотрудник\w+|таргетолог\w+|магазин\w+|склад\w+|позици\w+|бренд\w*|ступен\w+|колон\w+|'
        r'предпринимател\w+|направлен\w+|блок\w+|част\w+|ящик\w+|недел\w+|минут\w+|секунд\w+|'
        r'конкурент\w+|метод\w+|цифр\w+|клик\w+|пункт\w+|гипотез\w+|ход\w+|ходов|сервис\w+|итераци\w+')
ADJ = r'(?:\s+[а-яё]+(?:ых|ые|ой|ая|ое|ого|ому|ыми|ную|ных|ний|них))?'   # «50 [товарных] категорий»

ALLW = sorted(set(list(NUM) + list(MULT)), key=len, reverse=True)
SEQ = r'(?<![\w-])((?:' + "|".join(ALLW) + r')(?:[  ](?:' + "|".join(ALLW) + r'))*)(?![\w-])'

def render(phrase):
    """'сто пятьдесят миллиардов' → '150 миллиардов' ; 'сорок семь' → '47'"""
    ws = phrase.split()
    mult = None
    if ws and ws[-1].lower() in MULT:
        mult = MULT[ws[-1].lower()]; ws = ws[:-1]
    if not ws:
        return None
    total = 0
    for w in ws:
        if w.lower() not in NUM: return None
        total += NUM[w.lower()]
    if mult:
        return f"{total} {mult}" if total else None
    return str(total)

# Случаи, где автомат бессилен: эллипсис («не тридцать»), годы, метафора без единиц.
EXPLICIT = [
  # метафора чёрных ящиков — иначе выйдет разнобой: «80 копеек» цифрами, «два/десять» словами
  ("Из одного достаёте два. Из другого — десять. Из третьего — пятьдесят.",
   "Из одного достаёте 2. Из другого — 10. Из третьего — 50."),
  ("который на рубль отдаёт пятьдесят", "который на рубль отдаёт 50"),
  ("почему у него пятьдесят, а у меня два", "почему у него 50, а у меня 2"),
  # эллипсис: процент назван в предыдущей части фразы
  ("не тридцать, как считалось", "не 30, как считалось"),
  # годы — в разговорной форме, как он их и произносит
  ("В девяносто третьем", "В 93-м"),
  ("В семьдесят четвёртом", "В 74-м"),
  ("В восемьдесят четвёртом — семнадцать.", "В 84-м — 17%."),
  ("в пятьдесят девятом", "в 59-м"),
  # «на пяти» = на 5%: в этой же фразе уже стоит «5% — потолок», иначе разнобой внутри предложения
  ("годами живёт на пяти и объясняет", "годами живёт на 5% и объясняет"),
  # счёт «тысяча ходов → взять три → остальные 997»
  ("остальные девятьсот девяносто семь", "остальные 997"),
  # сквозной мотив «три пункта» — иначе «взять три. 3 пункта» в одной фразе
  ("Первые три перемножили", "Первые 3 перемножили"),
  ("Разрешите себе взять три.", "Разрешите себе взять 3."),
  ("Три внедрённых сильнее", "3 внедрённых сильнее"),
  ("три верхние строки", "3 верхние строки"),
  ("Пять пунктов, десять — неважно", "5 пунктов, 10 — неважно"),
]

def convert(text):
    props = []
    for a, b in EXPLICIT:
        if a in text:
            text = text.replace(a, b); props.append((a[:44] + "…", b[:44] + "…"))
    # 1) диапазоны: «пятьсот-семьсот», «сто двадцать — сто пятьдесят реклам»
    rng = re.compile(SEQ + r'\s*(?:-|—|–)\s*' + SEQ + r'(?=' + ADJ + r'\s*(?:' + UNIT + r'))', re.I)
    def _r(m):
        a, b = render(m.group(1)), render(m.group(2))
        if not a or not b or " " in a or " " in b: return m.group(0)
        props.append((m.group(0), f"{a}–{b}")); return f"{a}–{b}"
    text = rng.sub(_r, text)

    # 2) число (+прилагательное) + единица
    one = re.compile(SEQ + r'(?=' + ADJ + r'\s+(?:' + UNIT + r'))', re.I)
    def _o(m):
        ph = m.group(1); r = render(ph)
        if not r: return ph
        # одиночные «один/одна/одно/два/две/три» без множителя — риторика, не данные
        if len(ph.split()) == 1 and ph.lower() in ("один","одна","одно","одну","одного") : return ph
        props.append((ph, r)); return r
    text = one.sub(_o, text)

    # 3) «N процентов» → «N%»
    text = re.sub(r'(\d+)\s+процент\w*', lambda m: m.group(1) + "%", text)
    return text, props

src = open(f"{D}/scenario-clean.md", encoding="utf-8").read()
new, props = convert(src)

print(f"ЗАМЕН: {len(props)}\n" + "="*60)
for (a, b), c in Counter(props).most_common():
    print(f"  «{a}» → «{b}»" + (f"   ×{c}" if c > 1 else ""))

print("\n" + "="*60 + "\nОСТАЛОСЬ ПРОПИСЬЮ:\n" + "="*60)
shown = set()
for m in re.compile(SEQ, re.I).finditer(new):
    s = max(0, m.start()-46); e = min(len(new), m.end()+46)
    c = re.sub(r'\s+', ' ', new[s:e])
    if c in shown: continue
    shown.add(c); print(f"  [{m.group(1)}] …{c}…")

if "--apply" in sys.argv:
    for f in ["scenario-clean.md", "scenario-final.md", "review.html", ".blocks/v9.json"]:
        t = open(f"{D}/{f}", encoding="utf-8").read()
        t2, _ = convert(t)
        open(f"{D}/{f}", "w", encoding="utf-8").write(t2)
        print(f"✅ {f}")
    h = open(f"{D}/review.html", encoding="utf-8").read()
    b = json.loads(re.search(r'const BLOCKS = (\[.*?\n\]);', h, re.S).group(1))
    print(f"✅ review.html: JSON валиден, {len(b)} блоков")
else:
    print("\n(dry-run; запись: --apply)")
